#!/usr/bin/env python3
"""Rebuild src/audio-manifest.js from public/sfx/*.mp3 and public/music/*.mp3.
SFX files are named <id>.mp3 or <id>_1.mp3, <id>_2.mp3 ... (variants, one is picked at random each time)."""
import glob, json, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sfx = {}
for f in sorted(glob.glob(os.path.join(root, 'public/sfx/*.mp3'))):
    name = os.path.basename(f)
    m = re.match(r'^(.*?)(?:_(\d+))?\.mp3$', name); sfx.setdefault(m.group(1), []).append(name)
music = {os.path.basename(f)[:-4]: os.path.basename(f) for f in sorted(glob.glob(os.path.join(root, 'public/music/*.mp3')))}
open(os.path.join(root, 'src/audio-manifest.js'), 'w').write('// Generated by tools/sync-audio.py from public/sfx and public/music. Do not edit by hand.\nexport const SFX_FILES = ' + json.dumps(sfx, indent=1) + ';\nexport const MUSIC_FILES = ' + json.dumps(music, indent=1) + ';\n')
print(f'{len(sfx)} sound effects ({sum(len(v) for v in sfx.values())} files), {len(music)} music tracks')
